import test from 'node:test';
import assert from 'node:assert/strict';
import * as refs from './storyboardReferences.js';
import {promptHumanReviewSignature} from './promptReviewBatch.js';

test('published asset-following image recovers in place even after a manual prompt edit', () => {
 const ref={id:'asset:old',assetId:'asset',imageId:'old',projectId:'p',kind:'image',name:'陈大山',url:'old.png'};
 const assets=[{id:'asset',project_id:'p',adoptedImageId:'new',image_url:'new.png',images:[{id:'new',url:'new.png'}]}];
 const entry={id:'prompt',prompt:'原提示词',sceneId:'1-2'};
 const shot={sourcePromptId:'prompt',sourceContent:entry.prompt,storyboardPublicationId:'pub',generationConfig:{bindingVersionId:'v',bindingExpectedReferences:[ref.id]}};
 const decision={needs:[{visibility:'visible',cardUid:'card',imageId:'old',imageSelection:'asset'}]};
 const snapshot={entries:[entry],cards:[{uid:'card',assetId:'asset',sceneIds:['1-2']}]};
 const version={snapshot,decisions:{prompt:decision},reviews:{prompt:{published:true,signature:promptHumanReviewSignature(snapshot,entry,decision)}}};
 const binding={saved:{versions:{v:version}}};
 const value={prompt:'保留已编辑正文 @image1 @image2',references:[ref,{kind:'image',id:'other'}]};
 const fixed=refs.repairStoryboardAssetReferences(value,{shot,binding,assets,projectId:'p'});
 assert.equal(fixed.prompt,value.prompt);
 assert.deepEqual(fixed.references.map(ref=>ref.id),['asset:old','other']);
 assert.equal(fixed.references[0].imageId,'new');
 assert.equal(fixed.references[0].url,'new.png');
 assert.equal(fixed.references[0].followAdoptedImage,true);
 const noPointer=refs.repairStoryboardAssetReferences(value,{shot,binding,assets:[{...assets[0],image_url:''}],projectId:'p'});
 assert.equal(noPointer.references[0].imageId,'old');
 assert.equal(noPointer.references[0].followAdoptedImage,true);
 version.reviews.prompt.signature='unrelated-publication';
 assert.equal(refs.repairStoryboardAssetReferences(value,{shot,binding,assets,projectId:'p'}),value);
 decision.needs[0].imageSelection='explicit';
 assert.equal(refs.repairStoryboardAssetReferences(value,{shot,binding,assets,projectId:'p'}),value);
 assert.equal(refs.repairStoryboardAssetReferences(value,{shot,binding,assets,projectId:'foreign'}),value);
});
